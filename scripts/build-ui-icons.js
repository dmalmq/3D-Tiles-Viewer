// Writes src/icons.js: the Material Symbols Rounded glyphs the UI uses, as
// inline SVG strings. Fenrir's station-map screens (Figma
// gwyLPpmzk8c4ltvaxr47uM) draw their chrome with Material Symbols, so the
// editor and viewer do too. Add a name to ICONS and rerun
// `node scripts/build-ui-icons.js` to make another glyph available.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SYMBOLS_DIR = path.join(path.dirname(require.resolve("@material-symbols/svg-400/package.json")), "rounded");

const ICONS = [
  "add",
  "apartment",
  "check",
  "chevron_left",
  "chevron_right",
  "close",
  "dark_mode",
  "delete",
  "deployed_code",
  "download",
  "filter_center_focus",
  "folder",
  "folder_open",
  "folder_zip",
  "history",
  "keyboard_arrow_down",
  "language",
  "layers",
  "light_mode",
  "priority_high",
  "public",
  "search",
  "settings",
  "upload",
  "visibility",
  "visibility_off",
  "zoom_in_map",
];

function pathData(name) {
  const svg = readFileSync(path.join(SYMBOLS_DIR, `${name}.svg`), "utf8");
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length !== 1) throw new Error(`${name}: expected one path, found ${paths.length}`);
  return paths[0];
}

const entries = ICONS.map((name) => `  ${name}: "${pathData(name)}",`).join("\n");

writeFileSync(
  path.join(ROOT, "src", "icons.js"),
  `// Generated by scripts/build-ui-icons.js from @material-symbols/svg-400
// (Rounded, Apache-2.0). Do not edit by hand.

const PATHS = {
${entries}
};

export function icon(name, size = 16, className = "") {
  const d = PATHS[name];
  if (!d) throw new Error(\`Unknown icon: \${name}\`);
  const cls = className ? \` class="\${className}"\` : "";
  return \`<svg\${cls} width="\${size}" height="\${size}" viewBox="0 -960 960 960" fill="currentColor" aria-hidden="true"><path d="\${d}"/></svg>\`;
}
`,
);
console.log(`Wrote ${ICONS.length} icons to src/icons.js`);
